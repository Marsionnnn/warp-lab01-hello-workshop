Console.WriteLine("Podaj punkty życia");
int healthPoints = int.Parse(Console.ReadLine()!);
Console.WriteLine("Podaj liczbę mikstur");
int potions = int.Parse(Console.ReadLine()!);
Console.WriteLine("Czy bohater ma klucz? (true/false)");
bool hasKey = bool.Parse(Console.ReadLine()!);
Console.WriteLine("Czy bohater ma mapę? (true/false)");
bool hasMap = bool.Parse(Console.ReadLine()!);
bool isAlive = healthPoints > 0;
bool FullHealth = healthPoints == 100;
bool NeedHealth = healthPoints < 100;
bool HaveItems = potions > 0;
bool canEnterDungeon = hasKey || hasMap;
bool ReadyforBattle = isAlive && (FullHealth || NeedHealth) && HaveItems && canEnterDungeon;
Console.WriteLine("Żyje: " + isAlive);
Console.WriteLine("Ma pełny zdrowie: " + FullHealth);
Console.WriteLine("Potrzebuje zdrowia: " + NeedHealth);
Console.WriteLine("Ma mikstury: " + HaveItems);
Console.WriteLine("Może klucz lub mapę: " + canEnterDungeon);
Console.WriteLine("Gotowy do wyprawy: " + ReadyforBattle);